"""Regenerate src/registry.ts: static imports of every module and fixture JSON (Metro needs static imports)."""
import glob, os, re
from lib import ROOT

mods = sorted(os.path.basename(p) for p in glob.glob(os.path.join(ROOT, 'modules', '*.json')))
fx = sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(ROOT, 'fixtures', '*.json')))
ident = lambda s: 'm_' + re.sub(r'\W', '_', s[:-5])
fid = lambda s: 'f_' + re.sub(r'\W', '_', s)
lines = ['// Generated by authoring/register.py — do not edit by hand.', "import type { MachineSpec } from '@linux-learn/engine';", "import type { Module } from './schema';", '']
lines += [f"import {ident(m)} from '../modules/{m}';" for m in mods]
lines += [f"import {fid(f)} from '../fixtures/{f}.json';" for f in fx]
lines += ['', 'export const moduleList = [' + ', '.join(ident(m) for m in mods) + '] as unknown as Module[];', '']
lines += ['export const fixtureMap: Record<string, MachineSpec> = {'] + [f"  '{f}': {fid(f)} as unknown as MachineSpec," for f in fx] + ['};', '']
open(os.path.join(ROOT, 'src', 'registry.ts'), 'w').write('\n'.join(lines))
print(len(mods), 'modules,', len(fx), 'fixtures')
